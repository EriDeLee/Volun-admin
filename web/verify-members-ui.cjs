const { chromium } = require("playwright-core");
const fs = require("node:fs/promises");
const os = require("node:os");
const path = require("node:path");

(async () => {
  const output = path.join(os.tmpdir(), "volun-members-ui");
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ executablePath: "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const user = { username: "admin", name: "平台管理员", id: "00001", groups: ["super_admin"], status: "active", password_setup_required: false, has_password: true };
  const member = { ...user, username: "student", name: "测试成员", id: "00123", groups: ["formal_user"] };
  let pending = false;
  const basics = { name: "校园开放日志愿服务", department: "校团委", starts_on: "2026-11-12", ends_on: "2026-11-13", location: "学院路校区", sessions: [] };
  await page.route("**/api/v1/**", async (route) => {
    const url = new URL(route.request().url());
    let data;
    if (url.pathname.endsWith("/auth/me")) data = { user };
    else if (url.pathname.endsWith("/approvals")) data = { items: pending ? [{ project: { id: "p1", code: "ZY-2026-001" }, application: { id: "a1", kind: "initial", basics, applicant: "活动负责人", created_at: "2026-11-09T09:00:00Z", reason: "" } }] : [], total: pending ? 1 : 0, page_size: 20 };
    else if (url.pathname.endsWith("/admin/users")) data = { items: [user, member], total: 2, page: 1, page_size: 20, summary: { user_count: 2, active_count: 2, disabled_count: 0, manager_count: 1 } };
    else if (url.pathname.endsWith("/users/import")) data = { valid: true, imported: 0, rows: [{ line: 2, username: "student2", name: "新增成员", id: "00124", groups: ["formal_user"], error: "" }] };
    else throw new Error(`Unexpected API: ${url.pathname}`);
    await route.fulfill({ json: { errcode: 0, data } });
  });
  const shot = async (name) => {
    await page.screenshot({ path: path.join(output, `${name}.png`), fullPage: true });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
    if (overflow) throw new Error(`Horizontal page overflow: ${name}`);
  };
  await page.goto("http://127.0.0.1:5173/users");
  await page.getByRole("button", { name: "批量导入", exact: true }).click();
  await page.getByRole("textbox", { name: "CSV内容" }).waitFor();
  await shot("import-desktop");
  await page.getByRole("textbox", { name: "CSV内容" }).fill("账号,姓名,学号,初始密码,用户组\nstudent2,新增成员,00124,temporary-secret-123,formal_user");
  await page.getByRole("button", { name: "预检", exact: true }).click();
  await page.getByText("预检通过，共 1 人。").waitFor();
  await shot("preview-desktop");
  await page.setViewportSize({ width: 390, height: 844 });
  await shot("import-mobile");
  await page.getByRole("button", { name: "关闭弹窗" }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "添加成员", exact: true }).click();
  await shot("add-desktop");
  await page.setViewportSize({ width: 390, height: 844 });
  await shot("add-mobile");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "关闭弹窗" }).click();
  await page.getByRole("button", { name: "重置密码", exact: true }).nth(1).click();
  await shot("reset-desktop");
  await page.setViewportSize({ width: 390, height: 844 });
  await shot("reset-mobile");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole("button", { name: "关闭弹窗" }).click();
  await page.goto("http://127.0.0.1:5173/approvals");
  await page.getByRole("heading", { name: "暂无待审批申请" }).waitFor();
  await shot("approvals-empty-desktop");
  pending = true;
  await page.getByRole("button", { name: "刷新列表" }).click();
  await page.getByRole("link", { name: "查看并审批" }).waitFor();
  await shot("approvals-pending-desktop");
  await page.setViewportSize({ width: 390, height: 844 });
  await shot("approvals-mobile");
  await browser.close();
  console.log(`Verified desktop and mobile layouts. Screenshots: ${output}`);
})().catch((e) => { console.error(e); process.exitCode = 1; });
